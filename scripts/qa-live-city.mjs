// Verifies the rebuilt miniature against actual backend objects, not fixture financial state.
import {chromium,expect as baseExpect} from '@playwright/test';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
const api='http://127.0.0.1:8000',ui='http://127.0.0.1:5173',output=resolve('artifacts/live-city-integration');
const expect=baseExpect.configure({timeout:30000});
await mkdir(output,{recursive:true});
await build({stdin:{contents:"export {buildingPoint} from './apps/web/src/city/cityGeometry';",resolveDir:process.cwd()},outfile:resolve(output,'geometry.mjs'),bundle:true,format:'esm',platform:'node'});
const {buildingPoint}=await import(pathToFileURL(resolve(output,'geometry.mjs')).href);
const layout=JSON.parse(await readFile('apps/web/src/data/fixtures/sfCityLayout.json','utf8'));
async function request(path,body){const r=await fetch(api+path,body===undefined?{}:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});if(!r.ok)throw new Error(`${path}: HTTP ${r.status}`);return r.json();}
const samples=await request('/api/calibrations');samples.sort((a,b)=>b.collected_at.localeCompare(a.collected_at));
expect(samples.length).toBeGreaterThan(0);
const world=await request('/api/worlds',{scenario:'credit_crunch',calibration_id:samples[0].calibration_id});
const base=`/api/worlds/${world.simulation_id}`;
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1512,height:982}}),page=await context.newPage(),checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
const canvas=page.locator('.city-scene canvas'),button=name=>page.getByRole('button',{name,exact:true});
const pose=()=>canvas.evaluate(c=>({...c.dataset}));
const mark=name=>{checks.push(name);console.log('PASS',name);};
try{
 await page.addInitScript(({id,origin})=>{if(location.origin===origin)localStorage.setItem('economy-world',id);},{id:world.simulation_id,origin:new URL(ui).origin});
 await page.goto(ui);
 await expect(canvas).toHaveAttribute('data-bound-entities',String(world.entities.length));
 await expect(canvas).toHaveAttribute('data-mover-count','400');
 const initial=await pose();
 mark('Rebuilt geometry binds every default-world backend entity without inventing additional institutions');
 await button('Mission shops').click();
 await expect.poll(async()=>+(await pose()).cameraZoom).toBeCloseTo(4.6,2);
 const cafe=layout.buildings.find(b=>b.id==='cafe-14'),point=buildingPoint(cafe,cafe.x+cafe.w/2,cafe.y+cafe.d/2,cafe.h*.8);
 const rect=await canvas.boundingBox(),camera=await pose(),scale=+camera.baseScale*+camera.cameraZoom;
 await page.mouse.click(rect.x+rect.width/2+(point[0]-camera.cameraX)*scale,rect.y+rect.height/2+(point[1]-camera.cameraY)*scale);
 await expect(page.locator('.inspector h2')).toHaveText('Business 1');
 await expect(canvas).toHaveAttribute('data-lod','3');
 await page.screenshot({path:resolve(output,'shop-inspector.png')});
 mark('Featured cafe opens the actual Business 1 inspector and zooms to building focus');
 await button('Back to live events').click();
 await expect(page.locator('.district-feed-filter')).toContainText('Mission District');
 await button('Show whole-city events ×').click();await expect(page.locator('.district-feed-filter')).toHaveCount(0);
 mark('District navigation filters actual backend events and clears back to whole-city events');
 await button('Back to whole city').click();
 await page.getByRole('button',{name:'Trigger Crisis',exact:false}).click();
 const shockResponse=page.waitForResponse(r=>r.url().endsWith('/shocks')&&r.request().method()==='POST');
 await button('Apply bank shock').click();expect((await shockResponse).status()).toBe(200);
 const current=await request(base);
 const stressed=current.entities.filter(e=>e.kind==='bank'&&(e.status!=='active'||e.lending_available===false)).length;
 expect(stressed).toBeGreaterThan(0);
 await expect(canvas).toHaveAttribute('data-stressed-banks',String(stressed));
 expect((await pose()).mountId).toBe(initial.mountId);
 mark('Same-day bank losses refresh stress overlays from backend lending eligibility without remounting');
 await request(base+'/step',{ticks:12});
 await expect(canvas).toHaveAttribute('data-tick','12',{timeout:30000});
 const advanced=await request(base),closed=advanced.entities.filter(e=>e.kind==='business'&&e.status!=='active').length;
 expect(closed).toBeGreaterThan(0);
 await expect(canvas).toHaveAttribute('data-closed-businesses',String(closed));
 expect((await pose()).mountId).toBe(initial.mountId);
 expect((await pose()).staticRenders).toBe(initial.staticRenders);
 expect((await request(base+'/audit')).balanced).toBe(true);
 expect(advanced.calibration.sha256).toBe(world.calibration.sha256);
 await page.screenshot({path:resolve(output,'live-distress.png')});
 mark('Replacement world objects update business closures while static geometry and frozen public inputs stay intact');
 const response=page.waitForResponse(r=>r.url().endsWith('/forks')&&r.request().method()==='POST');await button('Fork Reality').click();
 expect((await (await response).json()).branches).toHaveLength(3);
 const download=page.waitForEvent('download');await button('Download comparison report').click();await (await download).saveAs(resolve(output,'comparison.html'));
 await button('Back to city').click();
 await page.setViewportSize({width:390,height:844});expect(await page.locator('body').evaluate(e=>e.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:resolve(output,'mobile.png')});
 expect(errors).toEqual([]);
 mark('Forks, report download and mobile layout work with the new renderer; no browser errors');
 await writeFile(resolve(output,'verification.json'),JSON.stringify({status:'passed',world:world.simulation_id,checks,errors},null,2));
}catch(error){await page.screenshot({path:resolve(output,'failure.png')}).catch(()=>{});throw error;}
finally{await context.close();await browser.close();}
